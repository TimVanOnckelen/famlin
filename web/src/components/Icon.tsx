export type IconName = keyof typeof ICON_PATHS;

export function Icon({
  name,
  size = 20,
  color = 'currentColor',
  strokeWidth = 2,
  // Only for the handful of icons with a meaningful "on" state (a saved
  // bookmark, a reacted heart) — everything else stays outline-only.
  filled = false,
  className,
  style,
}: {
  name: IconName;
  size?: number;
  color?: string;
  strokeWidth?: number;
  filled?: boolean;
  className?: string;
  style?: CSSProperties;
}) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill={filled ? color : 'none'}
      stroke={color}
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className}
      style={style}
      aria-hidden
    >
      {ICON_PATHS[name]}
    </svg>
  );
}
